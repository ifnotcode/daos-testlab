# Shared helpers for bin/lab (runs on the workstation, not on the lab host or the VMs).
# shellcheck shell=bash

LAB_ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)

log() { printf '\033[1m== %s\033[0m\n' "$*" >&2; }
warn() { printf 'WARNING: %s\n' "$*" >&2; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

# load_config [file]: lab.conf (+ lab.conf.local), or the given profile on top of lab.conf
load_config() {
	local conf=${1:-}
	# shellcheck source=../lab.conf
	source "$LAB_ROOT/lab.conf"
	if [ -n "$conf" ]; then
		[ -f "$conf" ] || die "no such config: $conf"
		# shellcheck disable=SC1090
		source "$conf"
		LAB_ID=$(basename "$conf" .conf)
	else
		[ -f "$LAB_ROOT/lab.conf.local" ] && source "$LAB_ROOT/lab.conf.local"
		LAB_ID=default
	fi
	SSH_KEY=${SSH_KEY/#\~/$HOME}
	WORK="$LAB_ROOT/work/$LAB_ID"
	mkdir -p "$WORK"
	HOST_WORK="${LAB_HOST_WORKDIR}/${LAB_ID}"
	# shared by all labs on the host
	HOST_BUILDS="${LAB_HOST_STORE:-$LAB_HOST_WORKDIR}/builds"
	HOST_CACHE="${LAB_HOST_STORE:-$LAB_HOST_WORKDIR}/cache"
	# RAM images of suspended VMs, per lab
	HOST_SAVED="${LAB_HOST_STORE:-$LAB_HOST_WORKDIR}/saved/$LAB_ID"
	write_ssh_config
	write_env_file
}

# vm_field <name> <field>: field of a VMS entry (name role ip mac vcpus ram disk image kernel)
vm_field() {
	local name=$1 field=$2 e n role ip mac cpus ram disk image kernel
	for e in "${VMS[@]}"; do
		read -r n role ip mac cpus ram disk image kernel <<<"$e"
		[ "$n" = "$name" ] || continue
		case $field in
		role) echo "$role" ;; ip) echo "$ip" ;; mac) echo "$mac" ;; cpus) echo "$cpus" ;;
		ram) echo "$ram" ;; disk) echo "$disk" ;; image) echo "$image" ;; kernel) echo "$kernel" ;;
		*) die "unknown VM field $field" ;;
		esac
		return 0
	done
	return 1
}

vm_names() { local e n; for e in "${VMS[@]}"; do read -r n _ <<<"$e"; echo "$n"; done; }
vms_with_role() { local n; for n in $(vm_names); do [ "$(vm_field "$n" role)" = "$1" ] && echo "$n"; done; true; }
server_vm() { vms_with_role server | head -1; }
is_vm() { vm_field "$1" role >/dev/null 2>&1; }

write_ssh_config() {
	local n known="$WORK/known_hosts"
	{
		echo "# generated by bin/lab from $LAB_ID config"
		echo "Host lab"
		echo "    HostName $LAB_HOST"
		echo "    User $LAB_HOST_USER"
		echo "    IdentityFile $SSH_KEY"
		echo "    IdentitiesOnly yes"
		echo "    ServerAliveInterval 30"
		for n in $(vm_names); do
			[ "$(vm_field "$n" role)" = talos ] && continue
			echo "Host $n"
			echo "    HostName $(vm_field "$n" ip)"
			echo "    User $VM_USER"
			echo "    IdentityFile $SSH_KEY"
			echo "    IdentitiesOnly yes"
			echo "    ProxyJump lab"
			echo "    StrictHostKeyChecking accept-new"
			echo "    UserKnownHostsFile $known"
			echo "    ServerAliveInterval 30"
		done
	} >"$WORK/ssh_config"
	SSH_CONFIG="$WORK/ssh_config"
}

# Environment for the scripts that run on the host and on the VMs
write_env_file() {
	local srv
	srv=$(server_vm)
	{
		echo "# generated by bin/lab from $LAB_ID config"
		declare -p VMS VM_USER LAB_NET_CIDR LIBVIRT_URI LIBVIRT_POOL LIBVIRT_POOL_DIR LIBVIRT_NET
		declare -p IMG_alma9 IMG_alma9_7 ALMA_VAULT
		declare -p DAOS_VERSION DAOS_REPO DAOS_REPO_KEY DAOS_SYSTEM DAOS_SCM_GB DAOS_BDEV_GB DAOS_TARGETS DAOS_RAM_RESERVED_GB DAOS_HUGEPAGES
		declare -p DAOS_PROVIDER SOFT_RDMA
		declare -p POOL POOL_SIZE CONT CONT_OWNER POOL_ACL_EXTRA CONT_ACL_EXTRA AGENT_DEFAULT_USER
		declare -p K8S_MINOR CONTAINERD_VER RUNC_VER CNI_VER GVISOR_RELEASE K8S_POD_CIDR
		declare -p TALOS_VERSION TALOS_CLUSTER TALOS_POD_CIDR TALOS_EXTENSIONS REGISTRY_PORT
		declare -p FTEST_SERVERS FTEST_CLIENTS
		echo "LAB_ID=$LAB_ID"
		echo "HOST_WORK=$HOST_WORK"
		echo "HOST_BUILDS=$HOST_BUILDS"
		echo "HOST_CACHE=$HOST_CACHE"
		echo "HOST_SAVED=$HOST_SAVED"
		echo "SERVER_VM=$srv"
		echo "SERVER_IP=$( [ -n "$srv" ] && vm_field "$srv" ip)"
		echo "REGISTRY=$( [ -n "$srv" ] && vm_field "$srv" ip):$REGISTRY_PORT"
	} >"$WORK/lab.env"
}

host_ssh() { ssh -F "$SSH_CONFIG" lab "$@"; }
# host command that runs podman: layers are staged in $TMPDIR (default /var/tmp, on the host's
# small root filesystem), so point it at the builds directory
host_podman() { host_ssh "mkdir -p $HOST_BUILDS/.tmp && export TMPDIR=$HOST_BUILDS/.tmp && $*"; }
vm_ssh() { local vm=$1; shift; ssh -F "$SSH_CONFIG" "$vm" "$@"; }
vm_scp() { scp -q -F "$SSH_CONFIG" "$@"; }

# Copy the given local paths (relative to LAB_ROOT) plus lab.env to <dest> on host or VM
push_files() {
	local target=$1 dest=$2 flags=--no-xattrs
	shift 2
	# macOS bsdtar: without file flags too, which GNU tar on the far side warns about
	tar --version 2>/dev/null | grep -q bsdtar && flags="$flags --no-fflags"
	# shellcheck disable=SC2086
	(cd "$LAB_ROOT" && COPYFILE_DISABLE=1 tar czf - $flags "$@" -C "$WORK" lab.env) |
		ssh -F "$SSH_CONFIG" "$target" "rm -rf $dest && mkdir -p $dest && tar xzf - -C $dest"
}

# Run a lab script on a VM as root: vm_run <vm> <script relative to LAB_ROOT> [args...]
vm_run() {
	local vm=$1 script=$2
	shift 2
	push_files "$vm" /tmp/testlab lib nodes tests
	vm_ssh "$vm" "sudo LAB_ENV=/tmp/testlab/lab.env bash /tmp/testlab/$script $*"
}

# Run a lab script on the libvirt host as the host user. Each call gets its own copy of the
# scripts, so that several lab commands can run at the same time.
host_run() {
	local script=$1 dir
	shift
	dir=$HOST_WORK/run/$$-$RANDOM
	push_files lab "$dir" lib host talos
	host_ssh "LAB_ENV=$dir/lab.env bash $dir/$script $*; rc=\$?; rm -rf $dir; exit \$rc"
}

wait_ssh() {
	local vm=$1 i
	for i in $(seq 1 90); do
		vm_ssh "$vm" -o ConnectTimeout=5 -o BatchMode=yes true 2>/dev/null && return 0
		sleep 5
	done
	die "$vm is not reachable over ssh"
}

wait_cloud_init() {
	vm_ssh "$1" 'for i in $(seq 1 120); do [ -f /var/lib/cloud/instance/boot-finished ] && exit 0; sleep 3; done; exit 1' ||
		die "cloud-init did not finish on $1"
}

vm_reboot() {
	local vm=$1
	vm_ssh "$vm" 'sudo systemctl reboot' 2>/dev/null || true
	sleep 15
	wait_ssh "$vm"
}
