#!/usr/bin/env bash
# DAOS client VM: client packages from the configured repositories and daos_agent (systemd)
# pointed at the lab server. Idempotent. Usage: daos-client.sh [--no-agent]
#   --no-agent  leave daos_agent disabled; also the case on Kubernetes nodes after "lab csi",
#               where the agent runs as a DaemonSet
source "$(dirname "$0")/../lib/remote.sh"

agent=1
[ "${1:-}" = --no-agent ] && agent=0
# "lab csi" leaves this marker: the agent DaemonSet serves the socket now
[ -f /etc/daos/testlab-agent-daemonset ] && agent=0

dnf -y -q install daos-client fuse3 libaio >/dev/null
id "$CONT_OWNER" >/dev/null 2>&1 || useradd -m "$CONT_OWNER"

{
	echo "# generated by daos-testlab"
	echo "name: $DAOS_SYSTEM"
	echo "access_points: ['$SERVER_VM']"
	echo "port: 10001"
	echo "transport_config:"
	echo "  allow_insecure: true"
	echo "log_file: /var/log/daos/daos_agent.log"
	echo "# only eth0 reaches the servers; without this the agent may hand out CNI interfaces"
	echo "include_fabric_ifaces: [eth0]"
	echo "# restarting the agent must not evict the pool handles of running dfuse instances"
	echo "disable_auto_evict: true"
	if [ -n "$AGENT_DEFAULT_USER" ]; then
		echo "# uids without a passwd entry (e.g. user-namespaced containers) get this principal"
		echo "credential_config:"
		echo "  client_user_map:"
		echo "    default:"
		echo "      user: ${AGENT_DEFAULT_USER%%:*}"
		echo "      group: ${AGENT_DEFAULT_USER##*:}"
	fi
} >/etc/daos/daos_agent.yml
cat >/etc/daos/daos_control.yml <<EOF
# generated by daos-testlab
name: $DAOS_SYSTEM
port: 10001
hostlist: ['$SERVER_VM']
transport_config:
  allow_insecure: true
EOF
mkdir -p /var/log/daos
chown daos_agent:daos_agent /var/log/daos 2>/dev/null || true
# dfuse --multi-user (allow_other) needs this
grep -q '^user_allow_other' /etc/fuse.conf || echo user_allow_other >>/etc/fuse.conf

if [ "$agent" = 1 ]; then
	systemctl enable --now daos_agent
	systemctl restart daos_agent
	for i in $(seq 1 20); do
		sudo -u "$CONT_OWNER" daos pool query "$POOL" >/dev/null 2>&1 && break
		sleep 3
		[ "$i" = 20 ] && die "pool $POOL is not reachable from $(hostname -s)"
	done
	log "client ready on $(hostname -s): $(rpm -q daos-client), pool $POOL reachable"
else
	systemctl disable --now daos_agent 2>/dev/null || true
	log "client packages installed on $(hostname -s), agent left disabled"
fi
