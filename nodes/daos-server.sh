#!/usr/bin/env bash
# DAOS server VM: single engine with SCM in RAM (tmpfs) and an AIO file as "NVMe", insecure
# transport, pool $POOL and POSIX container $CONT owned by $CONT_OWNER. Idempotent.
# Exits 100 when a reboot is needed first (transparent hugepages must be off for the engine).
source "$(dirname "$0")/../lib/remote.sh"

me=$(hostname -s)
dmg() { command dmg -o /etc/daos/daos_control.yml "$@"; }
as_owner() { sudo -u "$CONT_OWNER" "$@"; }

id "$CONT_OWNER" >/dev/null 2>&1 || useradd -m "$CONT_OWNER"
# libaio: the 2.8 RPMs do not pull it in, and daos_engine fails to start without it
dnf -y -q install daos-server daos-client daos-admin libaio >/dev/null

if ! grep -q 'transparent_hugepage=never' /proc/cmdline; then
	grubby --update-kernel=ALL --args=transparent_hugepage=never
	log "transparent_hugepage=never set, reboot needed"
	exit 100
fi

# Software RDMA (nodes/rdma.sh): rxe allows at most 32767 CQ entries, and libfabric's rxm sizes its
# CQs by FI_UNIVERSE_SIZE, which CaRT sets to 2048 unless given: the endpoint then fails to open
# ("Unable to create verbs CQ"). A small universe for the engine, and for the clients through
# client_env_vars, which the agent passes on with the attach info.
# (the extra lines carry their own newline: without them the file stays as it was)
client_env="" engine_env=""
case $DAOS_PROVIDER in
*verbs*)
	if [ -n "${SOFT_RDMA:-}" ]; then
		client_env=$'\nclient_env_vars: [FI_UNIVERSE_SIZE=64]'
		engine_env=$'\n    - FI_UNIVERSE_SIZE=64'
	fi
	;;
esac

cat >/etc/daos/daos_server.yml.new <<EOF
# generated by daos-testlab: single-node test server, no real PMem/NVMe
name: $DAOS_SYSTEM
port: 10001
mgmt_svc_replicas: ['$me']
provider: $DAOS_PROVIDER$client_env
control_log_mask: INFO
control_log_file: /tmp/daos_server.log
telemetry_port: 9191
transport_config:
  allow_insecure: true
# leave RAM for the OS; the rest is split between hugepages and SCM tmpfs
system_ram_reserved: $DAOS_RAM_RESERVED_GB
${DAOS_HUGEPAGES:+nr_hugepages: $DAOS_HUGEPAGES}
disable_vfio: true
engines:
-
  targets: $DAOS_TARGETS
  nr_xs_helpers: 0
  fabric_iface: eth0
  fabric_iface_port: 31416
  log_file: /tmp/daos_engine.0.log
  log_mask: INFO
  env_vars:
    - FI_SOCKETS_MAX_CONN_RETRY=1
    - FI_SOCKETS_CONN_TIMEOUT=2000$engine_env
  storage:
  -
    class: ram
    scm_mount: /mnt/daos
    scm_size: $DAOS_SCM_GB
  -
    class: file
    bdev_list: [/var/daos/bdev0]
    bdev_size: $DAOS_BDEV_GB
EOF
cat >/etc/daos/daos_control.yml <<EOF
# generated by daos-testlab
name: $DAOS_SYSTEM
port: 10001
hostlist: ['$me']
transport_config:
  allow_insecure: true
EOF
cat >/etc/daos/daos_agent.yml.new <<EOF
# generated by daos-testlab
name: $DAOS_SYSTEM
access_points: ['$me']
port: 10001
transport_config:
  allow_insecure: true
log_file: /tmp/daos_agent.log
# only eth0: the agent would also hand out podman0 (lab registry), which cannot reach the engine
include_fabric_ifaces: [eth0]
EOF
agent_changed=0
cmp -s /etc/daos/daos_agent.yml.new /etc/daos/daos_agent.yml || agent_changed=1
mv /etc/daos/daos_agent.yml.new /etc/daos/daos_agent.yml
mkdir -p /var/daos
chown daos_server:daos_server /var/daos
restart=0
cmp -s /etc/daos/daos_server.yml.new /etc/daos/daos_server.yml || restart=1
mv /etc/daos/daos_server.yml.new /etc/daos/daos_server.yml
systemctl enable daos_server
# a changed config, or an engine that died, needs a restart of the server
if [ "$restart" = 1 ] || ! pgrep -x daos_engine >/dev/null; then
	systemctl restart daos_server
fi

# Format: the control plane needs a few seconds after start; an already formatted system is fine
for i in $(seq 1 60); do
	dmg system query 2>/dev/null | grep -q 'Joined' && break
	out=$(dmg storage format 2>&1) && break
	echo "$out" | grep -qi 'already formatted\|system reformat requires\|invoked on a running system' &&
		break
	systemctl -q is-failed daos_server &&
		die "daos_server does not start: $(grep ERROR /tmp/daos_server.log | tail -2)"
	sleep 5
	[ "$i" = 60 ] && die "storage format failed: $out"
done
for i in $(seq 1 60); do
	dmg system query 2>/dev/null | grep -q 'Joined' && break
	[ "$i" -gt 6 ] && ! pgrep -x daos_engine >/dev/null &&
		die "daos_engine is not running: $(grep ' ERR ' /tmp/daos_engine.0.log | tail -3)"
	sleep 5
	[ "$i" = 60 ] && die "engine did not join"
done
systemctl enable --now daos_agent
[ "$agent_changed" = 1 ] && systemctl restart daos_agent

# Pool owned by the container owner (it then creates the container); root@ for dfuse on clients
if ! dmg pool list 2>/dev/null | grep -q "^$POOL "; then
	dmg pool create --size="$POOL_SIZE" --user="$CONT_OWNER@" --group="$CONT_OWNER@" "$POOL"
fi
for e in $POOL_ACL_EXTRA; do dmg pool update-acl "$POOL" --entry="$e" >/dev/null; done
if ! as_owner daos cont query "$POOL" "$CONT" >/dev/null 2>&1; then
	as_owner daos cont create "$POOL" "$CONT" --type=POSIX
fi
for e in $CONT_ACL_EXTRA; do as_owner daos cont update-acl "$POOL" "$CONT" --entry="$e" >/dev/null; done

# DAOS servers reply to the address a client advertises: route pod networks back to their nodes
conn=$(nmcli -g NAME,DEVICE connection show --active | awk -F: '$2 == "eth0" {print $1; exit}')
changed=0
while read -r cidr via; do
	[ -n "$cidr" ] || continue
	nmcli -g ipv4.routes connection show "$conn" | grep -q "$cidr $via" && continue
	nmcli connection modify "$conn" +ipv4.routes "$cidr $via"
	changed=1
done < <(pod_routes)
[ "$changed" = 1 ] && nmcli connection up "$conn" >/dev/null

log "DAOS server ready on $me: $(dmg pool list 2>/dev/null | grep "^$POOL " | tr -s ' ')"
as_owner daos cont get-acl "$POOL" "$CONT" | grep -v '^#' | sed 's/^/   /'
